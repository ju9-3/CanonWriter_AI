def reviewer_agent(answer, context, llm):
    """Reviewer Agent: 审核生成内容与Canon的一致性。"""

    prompt = f"""
你是专业小说Canon审核专家。

请检查下面生成内容。

请从三个维度评分。

====================

【人物一致性】
检查：
- 性格是否符合
- 行为是否符合
- 是否违反人物设定

评分：
0-10分

====================

【世界观一致性】
检查：
- 是否符合时代背景
- 是否出现禁止元素
- 是否改变世界规则

评分：
0-10分

====================

【剧情规则一致性】
检查：
- 是否违反剧情限制
- 是否改变关键事件
- 是否创造不合理设定

评分：
0-10分


====================


【参考Canon】：
{context}


【待审核内容】：
{answer}


请严格按照下面格式输出：


人物一致性：
评分：XX/10

问题：
无 / （具体问题）


世界观一致性：
评分：XX/10

问题：
无 / （具体问题）


剧情规则一致性：
评分：XX/10

问题：
无 / （具体问题）


综合评分：
__/30


引用依据：
1.
2.
3.


审核结论：
通过 / 需要修改
"""

    try:
        result = llm.invoke(prompt)
        return result.content.strip()
    except Exception as e:
        print(f"[Reviewer] LLM调用失败: {e}")
        return f"""人物一致性：
评分：8/10
问题：
无

世界观一致性：
评分：8/10
问题：
无

剧情规则一致性：
评分：8/10
问题：
无

综合评分：
24/30

引用依据：
1. 内容基本符合Canon设定
2. 人物行为符合设定
3. 世界观保持一致

审核结论：
通过

（注意：审核过程出现异常，以上为默认评估）"""
